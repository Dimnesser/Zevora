export const SKIN_MAP: Record<string, Skin> = Object.fromEntries(
  SKINS.map((s) => [s.id, s]),
);

export function getSkin(id: string): Skin {
  const skin = SKIN_MAP[id];
  if (!skin) throw new Error(`Unknown skin: ${id}`);
  return skin;
}

export function skinsByRarity(rarity: Skin["rarity"]): Skin[] {
  return SKINS.filter((s) => s.rarity === rarity);
}
